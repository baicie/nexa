test("TypeScript renderer uses explicit null for optional HandleRef fields", () => {
  const manifests = {
    common: structuredClone(common.manifest),
    ui: structuredClone(contracts.ui.manifest),
    system: structuredClone(contracts.system.manifest),
  };
  manifests.ui.types.push({
    name: "OptionalHandleFixture",
    kind: "record",
    fields: [
      {
        name: "anchor",
        type: "common.HandleRef",
        handleKind: "common.Node",
        optional: true,
      },
    ],
  });

  const typescript = renderTypeScriptProtocol(manifests);
  assert.match(typescript, /readonly anchor: Common\.HandleRef \| null/);
  assert.doesNotMatch(typescript, /readonly anchor\?: Common\.HandleRef/);
});

test("protocol generator writes once, then detects missing, changed, and unexpected artifacts", () => {
  const temporaryRoot = mkdtempSync(path.join(tmpdir(), "nexa-ui-protocol-codegen-"));
  try {
    assert.deepEqual(writeProtocolArtifacts({ root: temporaryRoot }), GENERATED_ARTIFACT_PATHS);
    assert.deepEqual(writeProtocolArtifacts({ root: temporaryRoot }), []);
    assert.doesNotThrow(() => checkProtocolArtifacts({ root: temporaryRoot }));

    const rustPath = path.join(temporaryRoot, "protocol/generated/protocol.rs");
    appendFileSync(rustPath, "// manual edit\n");
    assert.throws(
      () => checkProtocolArtifacts({ root: temporaryRoot }),
      /out of date: protocol\/generated\/protocol\.rs/,
    );

    writeProtocolArtifacts({ root: temporaryRoot });
    rmSync(rustPath);
    assert.throws(
      () => checkProtocolArtifacts({ root: temporaryRoot }),
      /missing: protocol\/generated\/protocol\.rs/,
    );

    writeProtocolArtifacts({ root: temporaryRoot });
    const unexpectedPath = path.join(temporaryRoot, "protocol/generated/stale.txt");
    mkdirSync(path.dirname(unexpectedPath), { recursive: true });
    writeFileSync(unexpectedPath, "stale\n");
    assert.throws(
      () => checkProtocolArtifacts({ root: temporaryRoot }),
      /unexpected: protocol\/generated\/stale\.txt/,
    );
  } finally {
    rmSync(temporaryRoot, { recursive: true, force: true });
  }
});

test("checked-in protocol artifacts are exact generator snapshots", () => {
  const artifacts = generateProtocolArtifacts();
  for (const [relativePath, expected] of Object.entries(artifacts)) {
    assert.equal(readFileSync(path.join(workspaceRoot, relativePath), "utf8"), expected);
  }
  assert.doesNotThrow(() => checkProtocolArtifacts({ root: workspaceRoot }));
});

test("generated Rust and TypeScript declarations compile", () => {
  const temporaryRoot = mkdtempSync(path.join(tmpdir(), "nexa-ui-protocol-compile-"));
  try {
    const rust = spawnSync(
      "rustc",
      [
        "--edition",
        "2021",
        "--crate-name",
        "nexa_protocol_generated",
        "--crate-type",
        "lib",
        "protocol/generated/protocol.rs",
        "--out-dir",
        temporaryRoot,
      ],
      { cwd: workspaceRoot, encoding: "utf8" },
    );
    assert.equal(rust.status, 0, rust.stderr || rust.stdout);

    const pnpm = process.platform === "win32" ? "pnpm.cmd" : "pnpm";
    const typescript = spawnSync(
      pnpm,
      [
        "exec",
        "tsc",
        "--noEmit",
        "--target",
        "ES2022",
        "--module",
        "NodeNext",
        "--moduleResolution",
        "NodeNext",
        "--strict",
        "--skipLibCheck",
        "packages/protocol/src/index.ts",
      ],
      { cwd: workspaceRoot, encoding: "utf8" },
    );
    assert.equal(typescript.status, 0, typescript.stderr || typescript.stdout);
  } finally {
    rmSync(temporaryRoot, { recursive: true, force: true });
  }
});

test("protocol codegen CLI exposes a clean --check drift gate", () => {
  const result = spawnSync(process.execPath, [generatorPath, "--check"], {
    cwd: workspaceRoot,
    encoding: "utf8",
  });
  assert.equal(result.status, 0, result.stderr || result.stdout);
  assert.match(result.stdout, /Protocol artifacts are up to date\./);
});
